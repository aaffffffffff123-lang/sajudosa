  function context(R,out){
    const r=R.reading,a=r.a,W=R.western&&R.western.available?R.western:null;
    const lv=f=>a.families[f].level,hi=f=>['strong','excess'].includes(lv(f)),lo=f=>['weak','absent'].includes(lv(f));
    const has=f=>lv(f)!=='absent',vis=f=>(a.families[f].visible||0)>0,ten=g=>(a.visibleTen&&a.visibleTen[g])||0;
    const weak=['신약','극약'].includes(a.strength.label),strong=['신강','극강'].includes(a.strength.label);
    const inter=(kind,pos)=>(a.interactions||[]).some(x=>x.kind===kind&&(pos==null||(x.positions||[]).includes(pos)));
    const sin=k=>(r.sinsal||[]).some(s=>s.key===k);
    const P=id=>(W&&W.planets.find(p=>p.id===id))||{};
    const house=id=>P(id).house||null,sign=id=>Number.isInteger(P(id).sign)?P(id).sign:null;
    const el=id=>{const s=sign(id);return s==null?null:['fire','earth','air','water'][s%4];};
    const asp=(x,y,angles)=>!!W&&(W.aspects||[]).some(q=>((q.a===x&&q.b===y)||(q.a===y&&q.b===x))&&angles.includes(q.angle));
    const inHouse=n=>W?W.planets.filter(p=>p.house===n).length:0;
    const cause=id=>(out.domains.find(d=>d.id===id)||{}).cause;
    return {hi,lo,has,vis,ten,weak,strong,inter,sin,house,sign,el,asp,inHouse,cause,core:out.core&&out.core.cause,coreRule:out.core&&out.core.rule||''};
  }
  function hit(x,c,cause){
    return !x.not.includes(cause)&&!(x.workNot||[]).includes(c.cause('work'))&&!(x.coreNot||[]).includes(c.core)&&!(x.skip&&x.skip(c))&&!!x.when(c);
  }
  // 칸마다 [장면, 원래 이치, 조건 맞는 문단…]을 문단으로 두고 팔자 줄로 닫는다. 재물은 [유형 장면, 유형 한 방, 문단…, 격차]로 닫는다.
  function weave(out,R){
    const c=context(R,out);
    out.domains.forEach(d=>{
      const pool=(POOL[d.id]||[]).filter(x=>hit(x,c,d.cause));
      d.poolIds=pool.map(x=>x.id);
      if(d.id==='money'){
        const lead=d.cause==='comfort'?[COPY.living,COPY.spending]:LEAD[d.cause]||[d.detail,d.rule];
        d.paragraphs=lead.concat(pool.map(x=>x.text),[COPY.stability]).filter(Boolean);
      }else d.paragraphs=[d.detail,d.rule].concat(pool.map(x=>x.text)).filter(Boolean);
      d.closing=d.fates.slice();
    });
    return out;
  }
  return {COPY,LEAD,POOL,context,weave};
